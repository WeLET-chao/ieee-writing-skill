#!/usr/bin/env python3
"""Generate writing_plan.md, figure_asset_plan.json, and TeX scaffold from scoping decisions."""

from __future__ import annotations

import argparse
import json
import re
from pathlib import Path
from typing import Any


def _skill_root() -> Path:
    """Return the ieee-manuscript-scoping skill directory."""
    return Path(__file__).resolve().parents[1]


def _load_json(path: Path) -> dict[str, Any]:
    """Load a JSON object from disk."""
    return json.loads(path.read_text(encoding="utf-8"))


def _slug_label(name: str) -> str:
    """Convert a section title to a LaTeX label slug."""
    text = name.lower().strip()
    text = re.sub(r"[^a-z0-9]+", "_", text).strip("_")
    return f"sec:{text or 'section'}"


def _figure_env_block(fig: dict[str, Any]) -> str:
    """Return a commented LaTeX figure placeholder block."""
    col = str(fig.get("column_span", "single")).lower()
    width = "0.76\\textwidth" if col == "double" else "\\columnwidth"
    env = "figure*" if col == "double" else "figure"
    file_path = fig.get("file", "figures/placeholder.pdf")
    fig_id = fig.get("id", "Fig. 1")
    claim = fig.get("claim", "")
    label = re.sub(r"[^a-zA-Z0-9]+", "_", fig_id).strip("_").lower()
    return f"""% {fig_id} — {claim}
% source_type: {fig.get("source_type", "")} | repo: {fig.get("repo_path", "")} | status: {fig.get("status", "")}
%\\begin{{{env}}}[!t]
%    \\centering
%    \\includegraphics[width={width}]{{{file_path}}}
%    \\caption{{SCOPE: {claim}}}
%    \\label{{fig:{label}}}
%\\end{{{env}}}
"""


def _table_block(table: dict[str, Any]) -> str:
    """Return a commented LaTeX table placeholder block."""
    table_id = table.get("id", "Table I")
    claim = table.get("claim", "")
    repo_path = table.get("repo_path", "")
    return f"""% {table_id} — {claim}
% source_type: {table.get("source_type", "")} | repo: {repo_path} | status: {table.get("status", "")}
%\\begin{{table}}[!t]
%    \\centering
%    \\caption{{SCOPE: {claim}}}
%    \\label{{tab:{re.sub(r"[^a-zA-Z0-9]+", "_", table_id).strip("_").lower()}}}
%    \\begin{{tabular}}{{lc}}
%        \\toprule
%        Parameter & Value \\\\
%        \\midrule
%        % TODO: fill from {repo_path}
%        \\bottomrule
%    \\end{{tabular}}
%\\end{{table}}
"""


def _render_sections_tex(sections: list[dict[str, Any]]) -> str:
    """Build LaTeX section blocks with bullet comment stubs."""
    parts: list[str] = []
    for section in sections:
        name = str(section.get("name", "Section"))
        label = str(section.get("label") or _slug_label(name))
        parts.append("%----------------------------------------------------------------------")
        parts.append(f"\\section{{{name}}}")
        parts.append(f"\\label{{{label}}}")
        parts.append("%----------------------------------------------------------------------")
        parts.append("")
        for bullet in section.get("bullets", []):
            parts.append(f"% SCOPE: {bullet}")
        parts.append("")
    return "\n".join(parts)


def _render_writing_plan(decisions: dict[str, Any]) -> str:
    """Render writing_plan.md content from scoping decisions."""
    venue = decisions.get("venue", "")
    page_limit = decisions.get("page_limit", "")
    main_tex = decisions.get("main_tex", "main.tex")
    title = decisions.get("title", "")
    evidence = decisions.get("evidence_boundary", "")
    sim = decisions.get("simulation_defaults", {})
    config = sim.get("config", "") if isinstance(sim, dict) else ""
    script = sim.get("script", "") if isinstance(sim, dict) else ""
    slugs = decisions.get("literature_slugs", [])

    lines = [
        "# Writing Plan",
        "",
        "Generated by `ieee-manuscript-scoping`. Update as the manuscript evolves.",
        "",
        "## Target",
        "",
        f"- **Venue:** {venue}",
        f"- **Page limit:** {page_limit}",
        f"- **Main TeX:** `paper/{main_tex}`",
        f"- **Title:** {title}",
        "",
        "## Narrative (problem → gap → method → evidence → so what)",
        "",
        "1. **Problem:** <!-- from README + literature -->",
        "2. **Gap in prior work:** <!-- from literature analysis.md -->",
        "3. **Proposed method:** <!-- wrapper / algorithm / workflow -->",
        "4. **Strongest evidence (numbers):** <!-- cite setup from configs -->",
        "5. **So what:** <!-- designer-facing impact -->",
        "",
        "## Contributions",
        "",
    ]
    for idx, item in enumerate(decisions.get("contributions", []), start=1):
        lines.append(f"{idx}. {item}")
    lines.extend(
        [
            "",
            "## Evidence boundary",
            "",
            evidence or "<!-- metrics and plots in scope vs omitted -->",
            "",
            "## Section outline",
            "",
        ]
    )
    for section in decisions.get("sections", []):
        lines.append(f"### {section.get('name', 'Section')}")
        lines.append("")
        for bullet in section.get("bullets", []):
            lines.append(f"- {bullet}")
        lines.append("")
    lines.extend(
        [
            "## Figures and tables",
            "",
            "| ID | File | Claim | Source | Repo path | Status |",
            "|----|------|-------|--------|-----------|--------|",
        ]
    )
    for asset in list(decisions.get("figures", [])) + list(decisions.get("tables", [])):
        lines.append(
            f"| {asset.get('id', '')} | {asset.get('file', '')} | {asset.get('claim', '')} | "
            f"{asset.get('source_type', '')} | {asset.get('repo_path', '')} | {asset.get('status', '')} |"
        )
    lines.extend(["", "## Simulation and reproduction", "", "```bash"])
    if script:
        lines.append(f"python {script}")
    if config:
        lines.append(f"# parameters: {config}")
    if not script and not config:
        lines.append("# add canonical reproduce commands")
    lines.extend(["```", "", "## Literature slugs used", ""])
    for slug in slugs:
        lines.append(f"- `{slug}` → `paper/literature/{slug}/analysis.md`")
    if not slugs:
        lines.append("- <!-- none yet; run ieee-literature-pipeline -->")
    lines.extend(
        [
            "",
            "## Handoff",
            "",
            "- [ ] `ieee-manuscript-figures` — plot scripts + paper/figures/ (figure_asset_plan.json)",
            "- [ ] `ieee-manuscript-prose` — fill TeX `% SCOPE:` stubs",
            "- [ ] `ieee-manuscript-bib` — verify `\\cite{}` keys",
            "- [ ] `ieee-manuscript-layout` — compile",
            "- [ ] `ieee-manuscript-revision` — full polish",
            "",
        ]
    )
    return "\n".join(lines)


def _asset_plan(decisions: dict[str, Any]) -> list[dict[str, Any]]:
    """Merge figures and tables into a single asset plan list."""
    assets: list[dict[str, Any]] = []
    for item in decisions.get("figures", []):
        assets.append(dict(item))
    for item in decisions.get("tables", []):
        assets.append(dict(item))
    return assets


def _render_tex(decisions: dict[str, Any]) -> str:
    """Fill the manuscript scaffold template."""
    template_path = _skill_root() / "templates" / "manuscript_scaffold.tex"
    template = template_path.read_text(encoding="utf-8")
    keywords = decisions.get("keywords", [])
    if isinstance(keywords, list):
        kw_text = ", ".join(str(k) for k in keywords)
    else:
        kw_text = str(keywords)
    figures = decisions.get("figures", [])
    tables = decisions.get("tables", [])
    figure_blocks = "\n".join(_figure_env_block(fig) for fig in figures)
    table_blocks = "\n".join(_table_block(tbl) for tbl in tables)
    replacements = {
        "{{TITLE}}": str(decisions.get("title", "Paper Title")),
        "{{AUTHORS}}": str(
            decisions.get(
                "authors_placeholder",
                "Author~One$^{1}$ \\\\ $^{1}$Affiliation",
            )
        ),
        "{{ABSTRACT_STUB}}": str(decisions.get("abstract_stub", "SCOPE: abstract placeholder.")),
        "{{KEYWORDS}}": kw_text or "keyword one, keyword two",
        "{{SECTIONS}}": _render_sections_tex(decisions.get("sections", [])),
        "{{FIGURE_BLOCKS}}": figure_blocks,
        "{{TABLE_BLOCKS}}": table_blocks,
    }
    tex = template
    for key, value in replacements.items():
        tex = tex.replace(key, value)
    return tex


def scaffold_manuscript(
    repo_root: Path,
    decisions: dict[str, Any],
    *,
    refresh_plan: bool = False,
    bootstrap_tex: bool = True,
    force_tex: bool = False,
) -> dict[str, str]:
    """Write scoping artifacts under paper/.

    Args:
        repo_root: Repository root.
        decisions: Scoping decisions dict.
        refresh_plan: Replace writing_plan.md even if it exists.
        bootstrap_tex: Create main TeX when missing.
        force_tex: Overwrite main TeX when it exists.

    Returns:
        Dict of output paths written.
    """
    paper_dir = repo_root / "paper"
    paper_dir.mkdir(parents=True, exist_ok=True)
    out_scoping = paper_dir / "out" / "scoping"
    out_scoping.mkdir(parents=True, exist_ok=True)

    written: dict[str, str] = {}
    plan_path = paper_dir / "writing_plan.md"
    if refresh_plan or not plan_path.is_file():
        plan_path.write_text(_render_writing_plan(decisions), encoding="utf-8")
        written["writing_plan"] = str(plan_path)

    asset_path = paper_dir / "figure_asset_plan.json"
    asset_path.write_text(json.dumps(_asset_plan(decisions), indent=2), encoding="utf-8")
    written["figure_asset_plan"] = str(asset_path)

    main_name = str(decisions.get("main_tex", "main.tex"))
    tex_path = paper_dir / main_name
    if force_tex or (bootstrap_tex and not tex_path.is_file()):
        tex_path.write_text(_render_tex(decisions), encoding="utf-8")
        written["main_tex"] = str(tex_path)

    decisions_copy = out_scoping / "scoping_decisions.json"
    decisions_copy.write_text(json.dumps(decisions, indent=2), encoding="utf-8")
    written["scoping_decisions_copy"] = str(decisions_copy)
    return written


def main() -> int:
    """CLI entry point."""
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--repo-root", type=Path, required=True)
    parser.add_argument("--decisions", type=Path, required=True)
    parser.add_argument("--inventory", type=Path, default=None)
    parser.add_argument("--refresh-plan", action="store_true")
    parser.add_argument("--bootstrap-tex", action="store_true", default=True)
    parser.add_argument("--no-bootstrap-tex", action="store_false", dest="bootstrap_tex")
    parser.add_argument("--force-tex", action="store_true")
    args = parser.parse_args()

    repo_root = args.repo_root.resolve()
    decisions = _load_json(args.decisions.resolve())
    if args.inventory and args.inventory.is_file():
        _load_json(args.inventory.resolve())  # reserved for future merge hints

    written = scaffold_manuscript(
        repo_root,
        decisions,
        refresh_plan=args.refresh_plan,
        bootstrap_tex=args.bootstrap_tex,
        force_tex=args.force_tex,
    )
    for key, path in written.items():
        print(f"  {key}: {path}")
    if not written.get("main_tex"):
        print("  main_tex: skipped (file exists; use --force-tex to overwrite)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
